def lookup_oui(mac: str) -> str:
    """
    通过 MAC 地址 OUI（前3字节）查询厂商名称
    返回格式：'小米' 或空字符串（查不到时）
    """
    if not mac or ':' not in mac:
        return ""
    mac_lower = mac.lower().strip()
    prefix = ":".join(mac_lower.split(":")[:3])
    return OUI_MAP.get(prefix, "")


def format_device_name(mac: str, current_name: str = "未知") -> str:
    """
    根据当前设备名和 MAC 地址生成更友好的名称
    优先级：已知名 > OUI厂商 > 保持原样
    """
    if current_name not in ("未知", "未知设备", ""):
        return current_name
    oui_name = lookup_oui(mac)
    if oui_name:
        return f"{oui_name}设备"
    return current_name
